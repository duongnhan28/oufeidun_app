import {test,expect} from '@playwright/test';
import ExcelJS from 'exceljs';

test('report uses business date, excludes tomorrow draft and exports the unpaid order value including fees',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:/Chủ cửa hàng/}).click();
 await expect(page.locator('.product-card').first()).toBeVisible({timeout:45000});
 await page.getByLabel('Mã đơn hàng',{exact:true}).fill('REPORT-BUSINESS-DATE');
 await page.getByLabel('Ngày giờ đặt đơn',{exact:true}).fill('2040-10-22T23:59');
 await page.getByLabel('Tên khách hàng',{exact:true}).fill('Khách kiểm thử báo cáo');
 await page.getByLabel('Số điện thoại',{exact:true}).fill('0123456789');
 await page.getByRole('button',{name:'Thêm IP15-TR',exact:true}).click();
 await page.getByLabel('Chi phí khác (đ)',{exact:true}).fill('5000');
 await page.getByRole('button',{name:'Xác nhận bán',exact:true}).click();
 await page.getByRole('button',{name:'Xác nhận và trừ kho',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Đã xác nhận');
 await page.getByLabel('Mã đơn hàng',{exact:true}).fill('REPORT-TOMORROW-DRAFT');
 await page.getByLabel('Ngày giờ đặt đơn',{exact:true}).fill('2040-10-23T00:00');
 await page.getByLabel('Tên khách hàng',{exact:true}).fill('Khách nháp ngày mai');
 await page.getByLabel('Số điện thoại',{exact:true}).fill('0987654321');
 await page.getByRole('button',{name:'Thêm IP15-CNT',exact:true}).click();
 await page.getByRole('button',{name:'Lưu bản nháp',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Đã lưu bản nháp');
 await page.getByRole('button',{name:'Báo cáo',exact:true}).click();
 await page.getByLabel('Từ ngày',{exact:true}).fill('2040-10-22');
 await page.getByLabel('Đến ngày',{exact:true}).fill('2040-10-22');
 const stat=(label:string)=>page.locator('.stat').filter({hasText:label});
 await expect(stat('Tổng đơn hàng bán ra')).toContainText('1');
 await expect(stat('Doanh thu thuần')).toContainText('30.000đ');
 await expect(page.getByText('không phụ thuộc thanh toán',{exact:false})).toBeVisible();
 const reconciliation=page.locator('.report-panel').filter({has:page.getByRole('heading',{name:'Đối chiếu trong kỳ'})});
 await expect(reconciliation).toContainText('25.000đ');await expect(reconciliation).toContainText('5.000đ');await expect(reconciliation).toContainText('30.000đ');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Tải báo cáo Excel',exact:true}).click();
 const book=new ExcelJS.Workbook();await book.xlsx.readFile((await(await download).path())!);
 const rows:Record<string,unknown>={};book.getWorksheet('Tổng quan')!.eachRow(row=>{rows[row.getCell(1).text]=row.getCell(2).value;});
 expect(rows['Số đơn bán ra']).toBe(1);expect(rows['Doanh thu']).toBe(30000);expect(rows['Tiền sản phẩm sau trả hàng']).toBe(25000);expect(rows['Chi phí khác trong đơn']).toBe(5000);expect(rows['Tổng giá trị gồm chi phí khác']).toBe(30000);
 await page.screenshot({path:'test-results/report-business-date.png'});
 await page.getByLabel('Đến ngày',{exact:true}).fill('2040-10-23');await page.getByLabel('Từ ngày',{exact:true}).fill('2040-10-23');
 await expect(stat('Doanh thu thuần')).toContainText('0đ');await expect(stat('Tổng đơn hàng bán ra')).toContainText('0');
});
